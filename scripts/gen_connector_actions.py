#!/usr/bin/env python3
"""Generate contracts/connector_actions.json from the connector YAMLs.

Why this file exists: MCP tool names cannot contain dots. The pattern is
^[a-zA-Z0-9_-]{1,64}$ and Claude Code SILENTLY rewrites a dot to an underscore
rather than erroring, which breaks round-tripping without telling you. So the
permission string `github:pulls.comment` and the wire tool name `pulls_comment`
are different strings, and the mapping must be stored, not recomputed in four
places by four agents.

Run:  python scripts/gen_connector_actions.py
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "spec" / "examples" / "registry" / "connectors"
OUT = ROOT / "contracts" / "connector_actions.json"

MCP_NAME = re.compile(r"^[a-z0-9_-]{1,64}$")


def wire_name(action: str) -> str:
    """action -> MCP tool name. Lowercase, dots and dashes to underscore."""
    return re.sub(r"[^a-z0-9_]", "_", action.lower())


def main() -> int:
    if not SRC.is_dir():
        sys.exit(f"not found: {SRC}")

    connectors: dict = {}
    problems: list[str] = []

    for path in sorted(SRC.glob("*.connector.yaml")):
        doc = yaml.safe_load(path.read_text())
        name = doc["metadata"]["name"]
        spec = doc["spec"]
        url = spec.get("transport", {}).get("url", "")
        port = int(m.group(1)) if (m := re.search(r":(\d+)", url)) else None

        actions = []
        for a in spec["actions"]:
            act = a["name"]
            wire = wire_name(act)
            full = f"mcp__{name}__{wire}"
            if not MCP_NAME.match(wire):
                problems.append(f"{name}:{act} -> {wire!r} fails {MCP_NAME.pattern}")
            if len(full) > 128:
                problems.append(f"{full} is {len(full)} chars, over the 128 limit")
            actions.append({
                "permission": f"{name}:{act}",
                "action": act,
                "mcp_tool": wire,
                "prefixed": full,
                "risk": a.get("risk", "read"),
                "resources": a.get("resources", []),
            })

        connectors[name] = {
            "transport_url": url,
            "port": port,
            "auth_modes": sorted((spec.get("auth") or {}).keys()),
            "builtin": name in ("memory", "platform"),
            "actions": actions,
        }

    # Ports must be unique, or the second wrapper to start fails to bind and it
    # looks like a routing bug.
    ports: dict[int, str] = {}
    for cname, c in connectors.items():
        p = c["port"]
        if p is None:
            continue
        if p in ports:
            problems.append(f"port {p} claimed by both {ports[p]} and {cname}")
        ports[p] = cname

    payload = {
        "$comment": (
            "GENERATED by scripts/gen_connector_actions.py. Do not edit by hand. "
            "FROZEN CONTRACT: `permission` is the internal string used in .agent "
            "files, the resolver and the database. `mcp_tool` is the wire name on "
            "the MCP server. They differ because MCP tool names cannot contain "
            "dots. Read the mapping; never recompute it."
        ),
        "generated_from": "spec/examples/registry/connectors/*.connector.yaml",
        "mcp_name_pattern": "^[a-zA-Z0-9_-]{1,64}$",
        "ports": {str(k): v for k, v in sorted(ports.items())},
        "connectors": connectors,
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2) + "\n")

    total = sum(len(c["actions"]) for c in connectors.values())
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  {len(connectors)} connectors, {total} actions")
    print(f"  ports: {', '.join(f'{k}={v}' for k, v in sorted(ports.items()))}")
    renamed = [a for c in connectors.values() for a in c["actions"]
               if a["action"] != a["mcp_tool"]]
    print(f"  {len(renamed)} action names differ from their wire name, e.g.:")
    for a in renamed[:4]:
        print(f"    {a['permission']:<34} -> {a['mcp_tool']}")
    if problems:
        print("\nPROBLEMS:", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
